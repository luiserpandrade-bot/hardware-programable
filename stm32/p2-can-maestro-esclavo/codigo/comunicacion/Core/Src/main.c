  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */

  // Iniciar la recepción por UART con interrupción
  HAL_UART_Receive_IT(&huart2, &uart_rx_data, 1);

  // Iniciar el periférico CAN
  if (HAL_CAN_Start(&hcan1) != HAL_OK) {
      Error_Handler();
  }

  /* USER CODE END 2 */

  /* Infinite loop */
