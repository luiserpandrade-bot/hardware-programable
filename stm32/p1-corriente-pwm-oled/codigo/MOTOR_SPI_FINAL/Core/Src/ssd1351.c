void SSD1351_DrawText(uint8_t x, uint8_t y, const char *text,
                      uint16_t color, uint16_t bg, uint8_t scale) {
    while (*text) {
        char c = *text++;
        if (c < 32 || c > 127) c = '?';
        const uint8_t *bitmap = font5x8[c - 32];

        for (uint8_t col = 0; col < 5; col++) {
            uint8_t line = bitmap[col];
            for (uint8_t row = 0; row < 8; row++) {
                uint16_t px = x + col * scale;
                uint16_t py = y + row * scale;
                for (uint8_t dx = 0; dx < scale; dx++) {
                    for (uint8_t dy = 0; dy < scale; dy++) {
                        if (line & 0x01)
                            SSD1351_DrawPixel(px + dx, py + dy, color);
                        else
                            SSD1351_DrawPixel(px + dx, py + dy, bg);
                    }
                }
                line >>= 1;
            }
        }
        x += 6 * scale;
    }
}


