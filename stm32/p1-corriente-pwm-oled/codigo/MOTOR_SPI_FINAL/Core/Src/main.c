uint32_t last_press_time = 0;  // Antirrebote
volatile uint8_t step_count = 0;
const uint8_t duty_steps[6] = {0, 20, 40, 60, 80, 90};

void Set_PWM_Duty(uint8_t percent) {
    if (percent > 100) return;
    uint32_t pulse = (percent * (__HAL_TIM_GET_AUTORELOAD(&htim1) + 1)) / 100;
    __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_3, pulse);
}

void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin) {
    if (HAL_GetTick() - last_press_time < 50) return;  // Antirrebote

    if (GPIO_Pin == GPIO_PIN_1 && step_count < 5) {
        step_count++;
    } else if (GPIO_Pin == GPIO_PIN_2 && step_count > 0) {
        step_count--;
    }

    Set_PWM_Duty(duty_steps[step_count]);
    last_press_time = HAL_GetTick();
}

// Función para leer 2 bytes del sensor
uint16_t Read_Current_Raw(void) {
    uint8_t tx_dummy[2] = {0x00, 0x00};
    uint8_t rx_data[2] = {0};

    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_12, GPIO_PIN_RESET); // CS LOW
    HAL_SPI_TransmitReceive(&hspi2, tx_dummy, rx_data, 2, HAL_MAX_DELAY);
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_12, GPIO_PIN_SET);   // CS HIGH

    uint16_t raw = ((uint16_t)rx_data[0] << 8) | rx_data[1];

        int16_t current_raw = raw & 0x1FFF; // bits 12:0
        if (current_raw & 0x1000) {
            current_raw |= 0xE000; // Extiende signo si bit 12 está en 1
        }

        return current_raw;
}

int16_t Read_Current_Signed(void) {
    uint8_t tx_dummy[2] = {0x00, 0x00};
    uint8_t rx_data[2] = {0};

    // CS del sensor de corriente en PB12
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_12, GPIO_PIN_RESET); // CS LOW
    HAL_SPI_TransmitReceive(&hspi2, tx_dummy, rx_data, 2, HAL_MAX_DELAY);
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_12, GPIO_PIN_SET);   // CS HIGH

    uint16_t raw = ((uint16_t)rx_data[0] << 8) | rx_data[1];

    int16_t current_raw = raw & 0x1FFF; // bits 12:0
    if (current_raw & 0x1000) {
        current_raw |= 0xE000; // Extiende signo si bit 12 está en 1
    }

    return current_raw;
}




